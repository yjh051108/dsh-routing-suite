  // ============ 自动轮询 watch：build 产物变化 → 自动整包重载 ============
  // watch 源 = 配置 watches + 注入清单（registry）——注入即自动 watch，
  // 自重载后动态 watch 不丢失（registry 持久）；改代码 → build → ~1.5s 自动生效。
  const fingerprints = new Map<string, string>()
  // ⚠️ P1（压测发现③）：目录消失/悬空（junction 指向的源被删/改名）时
  // fingerprintOf 返回 null——若盲目跳过静默，目录反复消失/恢复会产生乒乓
  // reload 且虚增 ✓、无审计。这里抑制重载 + 审计一次（30s 节流防刷屏）。
  const lastDangleTs = new Map<string, number>()
  let reloading = false
  ctx.setInterval(() => {
    if (reloading) return
    const watchList: Array<{ dir: string; match: string }> = [...watches]
    for (const e of readRegistry()) {
      if (!watchList.some(w => w.dir === e.dir)) watchList.push({ dir: e.dir, match: e.name })
    }
    for (const w of watchList) {
      // 防自毁⑤：watch 自动重载永不触发注入器自重载（改注入器代码 → build →
      // 自动自杀无人兜底）；自重载只允许显式 dev_reload_package 调用。
      if (String(w.match).includes('dsh-super-injector')) continue
      const fp = fingerprintOf(join(w.dir, 'lib'))
      if (fp === null) {
        const now = Date.now()
        const prevDang = lastDangleTs.get(w.dir)
        if (prevDang === undefined || now - prevDang > 30000) {
          lastDangleTs.set(w.dir, now)
          auditLog('watch-dangling', `目录不可读，跳过自动重载（源被删/悬空 junction）: ${w.dir}`)
        }
        continue
      }
      lastDangleTs.delete(w.dir)
      const prev = fingerprints.get(w.dir)
      if (prev !== undefined && prev !== fp) {
        fingerprints.set(w.dir, fp)
        // ⚠️ 收紧（用户反馈：太自由容易自杀）：watch 自动重载前**预检新代码
        // 可加载**——build 半途/改错导致的损坏 lib 不可加载时拒绝重载（旧
        // 代码继续跑）+ 审计，而不是盲目重载把自己搞死（与手动自重载的
        // 预检拦截同一道防线）。
        reloading = true
        const libFile = join(w.dir, 'lib', 'index.js')
        const precheck = existsSync(libFile)
          ? ctx.loader.import(pathToFileURL(libFile).href, () => [])
            .then((ns: unknown) => { const probe = ctx.loader.unwrapExports(ns); return !!(probe && (typeof probe === 'function' || typeof probe.apply === 'function')) })
            .catch(() => false)
          : Promise.resolve(false)
        precheck.then((probeOk: boolean) => {
          if (!probeOk) {
            reloading = false
            auditLog('watch-precheck-blocked', `自动重载预检失败（新代码不可加载），保持旧代码: ${w.dir}`)
            logger.warn('[super-injector] 自动重载预检失败，跳过（旧代码继续运行）: %s', w.dir)
            return
          }
          // match 用于 entry 查找，dir 用于 URL 匹配（loadCache key 是 file URL）
          reloadPackage(w.match, w.dir)
            .then(r => logger.info('[super-injector] %s', r))
            .catch(e => logger.warn('[super-injector] %s', e instanceof Error ? e.stack : String(e)))
            .finally(() => { reloading = false })
        })
        return // 一轮只处理一个包，下轮继续
      }
      fingerprints.set(w.dir, fp)
    }
  }, intervalMs)

